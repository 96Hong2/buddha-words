/**
 * 연꽃 한 송이. 광고 한 편을 미리 치러 둔 표다.
 *
 * ── 왜 연꽃인가 ───────────────────────────────────────────────────────
 *
 * 처음에는 연잎으로 그렸다. 꽃은 앱 곳곳에서 이미 장식으로 쓰고 있어서 재화까지 꽃이면
 * 같은 모양이 두 뜻으로 선다고 봤다. 사용자가 연꽃으로 바꾸라고 했고(2026-09-21),
 * 그게 맞다: 이 앱의 이름과 아이콘이 이미 연꽃이라 **재화가 앱의 얼굴과 같은 모양일 때**
 * 무엇을 모으는지 설명 없이 읽힌다. 장식 연꽃은 선으로만 그려 단색이고, 이쪽은 분홍
 * 그라데이션이라 눈으로도 갈린다.
 *
 * ── 어떻게 그렸나 ─────────────────────────────────────────────────────
 *
 *   꽃잎 다섯   바깥 둘 · 안쪽 둘 · 가운데 하나. 뒤에서 앞으로 겹쳐 깊이를 준다
 *   그라데이션  꽃잎 끝이 연하고 아래로 갈수록 짙다. 실제 연꽃이 그렇다
 *   테두리      꽃잎마다 바닥색 얇은 선. 18px 에서도 다섯 장이 갈려 보인다
 *
 * 색은 여기서 고정하지 않는다. CSS 변수를 그라데이션 stop 으로 받아서, 놓이는 자리가
 * 정한다(짙은 버튼 위에서는 `.leaf-use__icon` 이 연한 쪽으로 뒤집는다).
 *
 * ⚠ **테두리는 `currentColor` 다.** 꽃잎을 가르는 이 선은 「놓인 면의 색」이라야 하는데,
 * `var(--surface)` 로 박아 두었더니 짙은 버튼 위에서도 밝은 크림색으로 남아 꽃잎과 대비가
 * 1.26 밖에 안 됐다. 다섯 장이 분홍 덩어리 하나로 뭉치는 자리였다. 이제 자리마다
 * `color` 로 면 색을 주면 그 색을 따라간다.
 *
 * 그라데이션 id 는 `useId()` 로 만든다. 한 화면에 칩·시트·버튼이 같이 서는데 id 를
 * 고정하면 브라우저가 첫 번째 것만 쓰고, 자리마다 색을 뒤집는 구조가 통째로 무너진다.
 * (React 19 의 id 는 `_r_0_` 형식이라 `url(#…)` 에 그대로 쓸 수 있다. 18 의 `:r0:` 은
 * 콜론 때문에 못 쓴다.)
 */

import { useId } from 'react';

export interface LotusIconProps {
  /** 한 변의 픽셀. 정사각이다 */
  size?: number;
  className?: string;
}

export function LotusIcon({ size = 20, className }: LotusIconProps) {
  /*
    한 화면에 이 아이콘이 여럿 선다(칩 · 시트 · 버튼 둘). 그라데이션 id 를 고정하면
    문서에 같은 id 가 여러 개 생기고, 브라우저는 첫 번째 것만 쓴다. 자리마다 색을
    뒤집는 구조라 그때 전부 첫 번째 자리의 색을 따라간다.
  */
  const gradientId = useId();

  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
    >
      <defs>
        <linearGradient id={gradientId} x1="12" y1="3.4" x2="12" y2="17.6" gradientUnits="userSpaceOnUse">
          <stop offset="0" stopColor="var(--leaf-grad-from, #E09FAB)" />
          <stop offset="1" stopColor="var(--leaf-grad-to, #9A4356)" />
        </linearGradient>
      </defs>

      {/* 꽃잎 다섯. 뒤(바깥)부터 그려야 앞장이 위로 겹친다 */}
      <g fill={`url(#${gradientId})`} stroke="currentColor" strokeWidth="0.55">
        {/* 바깥 왼쪽. 수면에 눕듯 거의 가로로 눕는다 */}
        <path d="M2.4 11.5c2.4-.2 4.3.3 5.7 1.5 1.1.9 1.7 2.2 1.8 3.9-2.4.2-4.3-.2-5.7-1.3-1.2-1-1.8-2.4-1.8-4.1z" />
        {/* 바깥 오른쪽 */}
        <path d="M21.6 11.5c0 1.7-.6 3.1-1.8 4.1-1.4 1.1-3.3 1.5-5.7 1.3.1-1.7.7-3 1.8-3.9 1.4-1.2 3.3-1.7 5.7-1.5z" />
        {/* 안쪽 왼쪽 */}
        <path d="M5.7 7.2c2.3.8 3.9 2 4.8 3.7.7 1.4.6 2.9-.2 4.6-2.3-.6-3.9-1.6-4.7-3-1.1-1.8-1-3.6.1-5.3z" />
        {/* 안쪽 오른쪽 */}
        <path d="M18.3 7.2c1.1 1.7 1.2 3.5.1 5.3-.8 1.4-2.4 2.4-4.7 3-.8-1.7-.9-3.2-.2-4.6.9-1.7 2.5-2.9 4.8-3.7z" />
        {/* 가운데. 가장 앞에 서서 위로 뻗는다 */}
        <path d="M12 3.9c1.8 2.3 2.7 4.4 2.7 6.3 0 1.8-.9 3.4-2.7 4.9-1.8-1.5-2.7-3.1-2.7-4.9 0-1.9.9-4 2.7-6.3z" />
      </g>
    </svg>
  );
}
