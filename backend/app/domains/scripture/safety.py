def contexts_of(
    text: str,
    *,
    abuse: bool = False,
    minor: bool = False,
    reported: Iterable[str] = (),
) -> frozenset[str]:
    """고민 글이 어떤 상태인지. 구절을 빼는 열쇠가 된다.

    `abuse` · `minor` 는 1층 rules 가 이미 세운 깃발이다. 여기서 다시 판정하지 않고 받는다.
    `reported` 는 1차 패스 모델이 신고한 ContextFlag 다. 서버 판정과 **합친다.**
    어느 한쪽이 세우면 선다. 둘 다 봐야 서로 놓친 것을 덮는다.
    """
    found: set[str] = set()
    if abuse or _any(RULES_ABUSE, text) or _any(ABUSE_STRONG, text):
        found.add("abuse_victim")
    elif _count(ABUSE_WEAK, text) >= 2:
        found.add("abuse_victim")
    if minor:
        found.add("minor")
    if _any(SELF_BLAME, text):
        found.add("self_blame_high")
    if _any(SELF_WORTH, text):
        found.add("self_worth_collapse")
    if _any(BEREAVEMENT, text):
        found.add("bereavement")
    if _any(BREAKUP_STRONG, text) or _count(BREAKUP_WEAK, text) >= 2:
        found.add("breakup")

    for flag in reported:
        if flag in CONCERN_CONTEXTS:
            found.add(flag)
        else:
            # 스키마가 묶어 두는 자리라 여기 오면 안 된다. 조용히 버리지 않고 남긴다
            log.warning("unknown_context_flag", extra={"event": "unknown_context_flag"})
    return frozenset(found)


