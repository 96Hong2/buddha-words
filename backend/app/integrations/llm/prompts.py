def pass1_user(text: str, candidates: list[dict[str, str]]) -> str:
    """후보 하나에 두세 줄. 마지막 줄 「이럴 때」가 `retrieval_text` 다.

    「이럴 때」는 구절이 어떤 상황에 서는지를 평서문으로 적어 둔 검색 전용 문단이라
    게송보다 고민 글과 훨씬 잘 만난다(계획 02 3-3). 후보 상한이 20개라 이걸 실어도
    프롬프트는 예전의 10분의 1이 안 된다.
    """
    lines = []
    for c in candidates:
        lines.append(f"- {c['id']} | {c.get('citation', '')}")
        lines.append(f"  쉬운 뜻: {c.get('modern_gloss', '')}")
        situation = c.get("retrieval_text", "")
        if situation:
            lines.append(f"  이럴 때: {situation}")
    pool = "\n".join(lines) if lines else "(후보 없음)"
    return f"""{_wrap_concern(text)}

<고를_수_있는_경전_후보>
{pool}
</고를_수_있는_경전_후보>

이 목록 밖의 id 를 적지 마세요."""


